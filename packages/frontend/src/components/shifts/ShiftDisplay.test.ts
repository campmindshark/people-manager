function generatedSchedule(
  kind: 'chore' | 'event' | 'dinner',
  name: string,
): Schedule {
  const schedule = new Schedule(12, name, 'Generated schedule');
  schedule.chorePlanID = 4;
  schedule.plannerKey = `${kind}|${name}`;
  return schedule;
}

function adminSignupStatus(
  id: number,
  firstName: string,
  lastName: string,
  counts: { chore: number; event: number; dinner: number },
): SignupStatus {
  const status = NewPlaceholderSignupStatus();
  status.user = User.fromJson({ id, firstName, lastName });
  status.hasSignedUpForRoster = true;
  status.requirements = { chore: 3, event: 1, dinner: 1 };
  status.choreShiftCount = counts.chore;
  status.eventShiftCount = counts.event;
  status.dinnerShiftCount = counts.dinner;
  status.shiftCount = counts.chore + counts.event + counts.dinner;
  return status;
}

function shiftViewModel(
  plannerKey: string,
  id = 34,
  startTime = new Date('2026-08-23T15:00:00.000Z'),
): ShiftViewModel {
  const shift = new Shift(
    id,
    12,
    startTime,
    new Date(startTime.getTime() + 60 * 60 * 1000),
    2,
  );
  shift.plannerKey = plannerKey;
  return {
    shift,
    scheduleName: 'Kitchen cleanup',
    participants: [],
    signupOpen: false,
  };
}

function choreSignupShift(
  name: string,
  day: number,
  id: number,
  participants: User[] = [],
): GeneratedSignupShift {
  const generatedShift = generatedSignupShift(
    generatedSchedule('chore', name),
    {
      ...shiftViewModel(
        `chore|${day}|${name}`,
        id,
        new Date(Date.UTC(2026, 7, 22 + day, 15)),
      ),
      participants,
      signupOpen: true,
    },
  );

  if (!generatedShift) {
    throw new Error('Expected a generated signup shift.');
  }
  return generatedShift;
}

function renderSignupCategory(
  currentUser: User,
  shifts: GeneratedSignupShift[],
  shiftClient: BackendShiftClient,
  onSignupComplete: () => Promise<void>,
) {
  const signupCategory = React.createElement(SignupCategory, {
    allShifts: shifts,
    kind: 'chore',
    requirement: 3,
    onSignupComplete,
    shiftClient,
    shifts,
  });
  const TestRecoilRoot = RecoilRoot as React.ComponentType<{
    children?: React.ReactNode;
    initializeState: (mutableSnapshot: MutableSnapshot) => void;
  }>;
  render(
    React.createElement(
      TestRecoilRoot,
      { initializeState: ({ set }) => set(UserState, currentUser) },
      signupCategory,
    ),
  );
}

