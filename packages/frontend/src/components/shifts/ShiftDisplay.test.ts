test('atomically changes a current shift to an open replacement', async () => {
  const currentUser = User.fromJson({
    id: 7,
    firstName: 'Leslie',
    lastName: 'Knope',
    playaName: 'Waffles',
  });
  const signedUpUser = User.fromJson({
    id: 7,
    firstName: 'Leslie',
    lastName: 'Knope',
    playaName: 'Waffles',
  });
  const shifts = [
    choreSignupShift('Kitchen cleanup', 1, 34, [signedUpUser]),
    choreSignupShift('Trash patrol', 2, 35, [signedUpUser]),
    choreSignupShift('Greeter', 3, 36, [signedUpUser]),
    choreSignupShift('Replacement', 1, 37),
  ];
  shifts[3].shiftViewModel.signupRestrictionReason =
    SHIFT_SIGNUP_RESTRICTION_MESSAGES.existingShiftConflict;
  shifts[3].shiftViewModel.signupConflictShiftIDs = [34];
  const shiftClient = new BackendShiftClient('');
  const unregister = jest.spyOn(shiftClient, 'UnregisterFromShift');
  const signup = jest.spyOn(shiftClient, 'SignUpForShifts');
  const change = jest
    .spyOn(shiftClient, 'EditChoreSignup')
    .mockResolvedValue({ addedShiftIDs: [37], removedShiftIDs: [34] });
  const onSignupComplete = jest.fn().mockResolvedValue(undefined);
  renderSignupCategory(currentUser, shifts, shiftClient, onSignupComplete);

  const replacementSpot = screen.getAllByRole('button', {
    name: /select open spot for replacement/i,
  })[0];
  expect(replacementSpot).toBeDisabled();

  fireEvent.click(
    screen.getByRole('button', {
      name: /remove your spot for kitchen cleanup/i,
    }),
  );
  expect(replacementSpot).toBeEnabled();
  expect(
    screen.getByText(
      'Select one open chore shift as your replacement. Your current spot is kept unless the change succeeds.',
    ),
  ).toBeVisible();

  fireEvent.click(replacementSpot);
  fireEvent.click(screen.getByRole('button', { name: 'Change shift' }));

  await waitFor(() => {
    expect(change).toHaveBeenCalledWith([37], [34]);
    expect(onSignupComplete).toHaveBeenCalledTimes(1);
  });
  expect(unregister).not.toHaveBeenCalled();
  expect(signup).not.toHaveBeenCalled();
  expect(await screen.findByText('Changed your chore shift.')).toBeVisible();
});

